export const adminCategories = shopCategories.map((category, index) => ({
  id: category.slug,
  name: category.title,
  slug: category.slug,
  products: catalogProducts.filter((product) => product.categorySlug === category.slug).length,
  live: index < 12,
}));

export const adminBrands = Array.from(
  catalogProducts.reduce((map, product) => {
    map.set(product.brand, (map.get(product.brand) ?? 0) + 1);
    return map;
  }, new Map<string, number>()),
).map(([name, products]) => ({ id: name.toLowerCase(), name, products, live: true }));

export const adminInventory = catalogProducts.map((product) => ({
  id: product.id,
  sku: product.sku,
  name: product.name,
  onHand: product.onHand ?? 0,
  reserved: 0,
  reorderAt: 2,
}));
